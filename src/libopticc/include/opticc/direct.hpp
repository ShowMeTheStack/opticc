#pragma once
#include <cstdint>
#include <string>
#include <vector>

namespace opticc::direct {

// 0.25 s (git uses 2 s, a margin for 1-s-resolution filesystems). What the margin must cover: the gap between the
// clock that stamps ctime (Linux: the coarse clock, at most one jiffy = 1–10 ms behind) and our wall clock, on the
// same machine. 2 s would exclude every TU that the build compiles within 2 s of regenerating a header; 0.25 s still
// exceeds any jiffy by 25×. Inputs on a network
// filesystem (server clock) are not supported by the direct path's racy rule — such builds should set
// OPTICC_DIRECT=off.
constexpr double kRacyS = 0.25;
constexpr size_t kMaxEntries = 8;

struct FStat { bool exists = false; bool is_dir = false; uint64_t dev = 0, ino = 0, size = 0; int64_t mtime_ns = 0, ctime_ns = 0; };

// The margin a "changed before t0?" ctime test needs on THIS machine (recording direct entries).
// Claim: a file whose ctime T satisfies T < t0 - m was last changed before wall time t0 — so before a compile that
// starts reading its inputs after t0 — when m >= the lag of the clock that stamps ctime behind CLOCK_REALTIME.
// Proof: a change at wall time t >= t0 is stamped T' > t - lag >= t0 - m > T, and no user call can set ctime, so the
// file's ctime would no longer be T. Linux stamps ctime with the coarse real-time clock (current_time(): at most one
// tick behind; finer with multigrain timestamps): m = 2 × clock_getres(CLOCK_REALTIME_COARSE) + 2 ms (≈ 4 ms at
// HZ=1000). Elsewhere, or when the resolution is unknown, m = kRacyS. A ctime without nanoseconds suggests a filesystem
// with 1-s (FAT: 2-s) timestamps, whose stamps are truncated: such files use kRacyCoarseS. Assumptions, as git's
// racy-clean rule: the files and the coordinator share one clock (not a network filesystem — set OPTICC_DIRECT=off
// there) and the clock is not stepped backwards during a build. OPTICC_RACY_S=<seconds> overrides m.
// With kRacyS for every file, an input regenerated by the build less than 0.25 s before its consumer's request
// (kbuild: av_permissions.h, crc32table.h, *.mod.c, .vmlinux.export.c, the kallsyms .S files, voffset.h, ...) would
// never be recorded, although its content is the same in every build.
constexpr double kRacyCoarseS = 2.25;
double racy_margin_s();
// Corollary: a client-local compile is started no earlier than request arrival + m (coordinator.cpp go_local), so
// every input written before the request arrived has ctime <= write time < t0 - m and passes; inputs generated
// immediately before their consumer (kbuild .tmp_vmlinux0.kallsyms.S, zoffset.h) are therefore recordable. Writes at or
// after t0 still fail this test.
bool changed_since(const FStat& f, double t0);
// t0 for changed_since() is read from the clock that STAMPS file times (Linux: the coarse
// real-time clock, CLOCK_REALTIME_COARSE = ktime_get_coarse_real; macOS/APFS: the fine real-time clock). A write that
// happens after t0 is read then carries ctime >= t0 because that clock never runs backwards (no lag bound between two
// clocks is needed, under virtualisation or otherwise); m only absorbs file-system timestamp truncation and
// clock steps. Assumptions: no backward step of the system clock during a build; timestamp granularity <= m.
double stamp_now();   // ctime >= t0 - margin (the entry must not be recorded)
// Compiler PROBES (input /dev/null or stdin; kbuild cc-option / as-instr / --version / -dM -E) are not direct
// entries: they have no source and, by construction, no file inputs outside the compiler installation. They are cached
// by opticc/probe.hpp (key = compiler + config-file identity, argv without the output path, cwd, env, input hash;
// value = rc, stdout, stderr, output bytes) — invariant and proof in probe.hpp.
// An entry recorded here is also PUBLISHED, in a machine-independent form (content hashes, no stat), to the worker
// tier; a fresh client's coordinator fetches and validates it by content on a local miss (opticc/rdirect.hpp, invariant
// and proof there).
FStat stat_path(const std::string& path);
// Stat many paths (best grouped by directory): one directory fd per run of paths in the same directory.
std::vector<FStat> stat_many(const std::vector<std::string>& paths);
bool same(const FStat& a, const FStat& b);   // exists, dev, ino, size, mtime_ns, ctime_ns

struct Pos { std::string path; FStat st; std::string sha; };        // sha: raw sha256 (hex) of the content used
struct NegGroup { std::string dir; FStat st; bool volatile_dir = false; std::vector<std::string> names; };
// keysha: Pos::sha is the COMMENT-INSENSITIVE key hash (cachekey::content_key_sha) instead of the raw sha256 —
// used when the compile keeps no comments and emits no debug info (cachekey::keeps_comments false), exactly the
// client cache's criterion: a comment-only edit that keeps every token's position yields a byte-identical object
// (test content_key_equal_implies_identical_object). A touched source or header then still hits in the wrapper.
struct Entry { std::string obj; std::vector<Pos> pos; std::vector<NegGroup> neg; double recorded_wall = 0; bool keysha = false; };
// The content hash used for positives and the source in the direct key: raw sha256, or the key hash when keysha.
std::string content_sha(const std::string& content, bool keysha);

// Identity of a compiler executable (path resolved through symlinks): cheap (stat only).
std::string compiler_identity(const std::string& resolved_path);
// Direct key. `env` is the list of include-affecting environment entries "NAME=value" (see relevant_env()).
std::string key(const std::string& compiler_identity, const std::vector<std::string>& argv, const std::string& cwd,
                const std::vector<std::string>& env, const std::string& source_sha);
std::vector<std::string> relevant_env();
// The key a direct entry is filed under: H(key | system-include stat signature). The wrapper
// reads the signature its live coordinator published; the coordinator records under the signature it held when the
// request arrived, and only if that is still current when it records.
std::string with_sysinc(const std::string& dkey0, const std::string& sysinc_sig);
// Arguments whose effect depends on files the direct path cannot track (response files, precompiled headers and
// modules, profile data, sanitizer lists, plugins, spec files, -B tool directories) or that write to a stream: a
// compile with any of them never uses the direct path (the coordinator path still serves it). Returns the offending
// argument in *why.
bool safe_args(const std::vector<std::string>& argv, std::string* why = nullptr);
// The compile's system include search can differ from the coordinator's default system directories (sysroot,
// target, toolchain, stdlib, builtin-include switches). Only matters when the dependency file omits system headers.
bool changes_system_search(const std::vector<std::string>& argv);

std::string manifest_path(const std::string& cache_dir, const std::string& dkey);
// Serialisation (exposed for tests).
std::string encode(const std::vector<Entry>& entries);
bool decode(const std::string& blob, std::vector<Entry>* entries);

// Lookup: returns the object key of the newest valid entry, or "" (no manifest / nothing valid). `why` (optional)
// receives a short reason on a miss. Hashes a positive file only when its stat differs.
std::string lookup(const std::string& cache_dir, const std::string& dkey, std::string* why = nullptr);
// Validate one entry (exposed for tests).
bool valid(const Entry& e, std::string* why = nullptr);
// As valid(), with the shared content-hash memo under <cache_dir>/h (see hash_memo_get) when cache_dir is set.
bool valid(const Entry& e, std::string* why, const std::string& cache_dir);

// SHARED CONTENT-HASH MEMO. A positive whose stat differs from the recorded one must be hashed; a file the build
// regenerates with the same bytes (LLVM's tablegen outputs after `ninja -t clean`: Attrs.inc, IntrinsicEnums.inc,
// X86GenInstrInfo.inc, ... MBs, included by hundreds of TUs) would be hashed again by EVERY hit. The memo keeps, per (path,
// hash kind), the stat and the hash of the bytes last hashed: <cache_dir>/h/<xx>/<sha256(kind|path)>.
// Written only when the file's ctime is older than (start of hashing - margin) and its stat did not change while it was
// hashed (git's racy-clean rule, direct.hpp changed_since): any later change then changes ctime, so a memo whose stat
// equals the file's current stat EXACTLY (dev, ino, size, mtime_ns, ctime_ns) holds the hash of its current bytes.
bool hash_memo_get(const std::string& cache_dir, const std::string& path, const FStat& now, bool keysha, std::string* sha);
void hash_memo_put(const std::string& cache_dir, const std::string& path, const FStat& st, bool keysha, const std::string& sha);

// Append an entry (dedup by object key; keep the newest kMaxEntries), written atomically (temp + rename).
void record(const std::string& cache_dir, const std::string& dkey, const Entry& e);

// Build the negative groups for a set of absent candidate paths (stat()s each parent directory now; a directory whose
// ctime >= t_start_wall - kRacyS is volatile). Returns false if a candidate exists now (caller must not record).
bool make_negative_groups(const std::vector<std::string>& absent, double t_start_wall, std::vector<NegGroup>* out);

double wall_now();

}  // namespace opticc::direct
