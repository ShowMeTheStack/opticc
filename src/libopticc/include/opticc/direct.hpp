// opticc: client-side DIRECT cache path (ccache's "direct mode", made exact and cheaper).
//
// Without it, every client-cache hit goes wrapper -> coordinator round trip -> include scan of the whole closure ->
// per-file key-hash check, while ccache answers inside each compiler process. The direct path lets the compiler wrapper
// answer a hit by itself, without the coordinator and without scanning or hashing headers:
//
//   direct key  D = sha256(format, compiler identity (resolved path, dev, ino, size, mtime_ns, ctime_ns), argv
//                   exactly as given, cwd, include-affecting environment, raw sha256 of the source bytes)
//   manifest    <cache>/d/<D[0:2]>/<D>  — up to kMaxEntries entries, newest last; each entry:
//                 object key O (an object of the existing client cache, <cache>/o/<O> + .meta)
//                 POSITIVE files: every file the compile read (scanner closure ∪ compiler dep file ∪ source), with
//                   (dev, ino, size, mtime_ns, ctime_ns) and the raw sha256 of the bytes the compile used
//                 NEGATIVE probes: every include-search candidate that did NOT exist when the compile ran (a header
//                   created there later would shadow the one used), grouped by parent directory with that
//                   directory's (dev, ino, mtime_ns, ctime_ns) — or "absent" when the directory itself did not exist
//
// Hit test (all must hold, newest entry first):
//   positive: exact stat match on all five fields, OR (same size and) raw sha256 of the current bytes == recorded sha
//             (keysha entries: the comment-insensitive key hash of the current bytes == recorded, any size)
//   negative group: the directory's stat is unchanged (no entry was created/removed/renamed in it), OR every probed
//                   name in it is still absent
// Recording rules (coordinator): an entry is written only if every positive file's ctime and every non-volatile
// negative directory's ctime is older than the compile's start minus kRacyS (git's racy-clean rule on ctime, which
// tools cannot set backwards). A directory whose ctime is recent (kbuild's filechk creates and deletes temp files in
// include/generated during every build) is recorded as VOLATILE: its probed names are always stat()ed individually.
// Consequences: a later modification of any input changes its ctime (> recorded ctime + kRacyS) -> the stat test fails
// -> content is compared byte-exactly; a newly created shadowing header changes its directory's mtime -> its name is
// stat()ed -> miss. System headers outside the compiler's dep-file output are pinned by the compiler identity (as in
// the rest of opticc's caches).
